"""
Manuscript drop-ins for the non-Transformer benchmark.

Every numeric value in the generated LaTeX is substituted from the computed
result tables; nothing is hard-coded. Sentences that describe qualitative
findings are selected by the computed values, so a different result produces a
different sentence rather than a stale claim.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Sequence

import numpy as np
import pandas as pd

from .necessity import DELETION_FRACTIONS
from .reporting import FAMILY_LABEL
from .sampling import PERIODS, REGIME_ORDER


def _num(value: object, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    try:
        f = float(value)
    except (TypeError, ValueError):
        return str(value)
    if not np.isfinite(f):
        return "n/a"
    return f"{f:.{digits}f}"


def _esc(text: str) -> str:
    return str(text).replace("_", r"\_")


def _range(series: pd.Series, digits: int = 3) -> str:
    s = pd.to_numeric(series, errors="coerce").dropna()
    if s.empty:
        return "n/a"
    if len(s) == 1:
        return _num(s.iloc[0], digits)
    return f"{_num(s.min(), digits)}--{_num(s.max(), digits)}"


#: short aliases used in the prose, mapped onto the computed table columns
_ALIASES = {
    "C": "contribution_score",
    "N": "necessity_score",
    "S": "structure_score",
    "D": "aggregate_diagnostic_score",
    "policy": "model_id",
    "weight_unique_rows": "unique_allocations",
}


def _view(table: pd.DataFrame) -> pd.DataFrame:
    """Add the short aliases used by the prose without touching the source table."""
    out = table.copy()
    for alias, column in _ALIASES.items():
        out[alias] = out[column] if column in out.columns else np.nan
    return out


def _policy_list(table: pd.DataFrame, family: str) -> str:
    sub = table.loc[table["family"] == family]
    names = [_esc(v) for v in sub["policy"]]
    if not names:
        return "none"
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + " and " + names[-1]


def methods_tex(
    table: pd.DataFrame,
    sample_sizes: pd.DataFrame,
    decision_targets: pd.DataFrame,
    settings: Dict[str, object],
) -> str:
    table = _view(table)
    n_dt = int((table["family"] == "DT").sum())
    n_rl = int((table["family"] == "RL").sum())
    algos = sorted(set(table.loc[table["family"] == "RL", "algorithm"]))
    n_dates = int(settings.get("n_common_sample_dates", 0))
    fractions = ", ".join(f"{int(f * 100)}\\%" for f in DELETION_FRACTIONS)

    counts = sample_sizes.loc[sample_sizes.get("regime", "") == "all", "n_diagnostic_sample"]
    same_n = bool(counts.nunique() <= 1) if len(counts) else False

    body = rf"""% Auto-generated by scripts/run_cross_architecture_comparison.py -- do not edit by hand.
\subsection{{Non-Transformer benchmark}}
\label{{sec:non-transformer-benchmark}}

The diagnostics introduced above are defined on quantities that any parametric policy
exposes: a differentiable scalar summarising the decision, the observation window that
produced it, and the activations of the intermediate layers. None of the three dimensions
requires attention weights or return-to-go conditioning. To establish that this is a
property of the framework rather than an artefact of the Decision Transformer, we apply the
identical procedure to conventional deep reinforcement-learning policies trained on the same
allocation problem.

\paragraph{{Policies.}} The comparison covers {n_dt} Decision Transformer
{'checkpoint' if n_dt == 1 else 'checkpoints'} and {n_rl} Stable-Baselines3
{'policy' if n_rl == 1 else 'policies'} ({', '.join(_esc(a) for a in algos)}), all frozen at
their released weights. No policy was retrained, no hyper-parameter was tuned and no
preprocessing statistic was refitted. Inclusion was decided by pre-specified technical
criteria---checkpoint loadability, presence of preprocessing metadata, compatibility with the
common asset universe, coverage of the evaluation period and existence of an
action-to-weight mapping---applied before any diagnostic was computed, so no policy enters or
leaves the comparison on the basis of its results. The resolved manifest, including every
exclusion and its reason, is released with the code.

\paragraph{{Common data and evaluation sample.}} All policies observe the same six equity
indices plus a cash instrument, derived from a single frozen market-data file, and are
evaluated over {PERIODS['eval'][0]}--{PERIODS['eval'][1]}. The diagnostic sample is drawn from
the trading dates available to every policy and is stratified across the four market regimes
({', '.join(name.replace('_', ' ') for name in REGIME_ORDER)}), giving {n_dates} common dates{' evaluated for every policy' if same_n else ''}.
Observation counts per policy and regime are reported in the supplement. Weights are
evaluated on the exchange trading calendar only; no calendar-day reindexing or forward filling
is applied.

\paragraph{{Architecture-specific decision targets.}} A single diagnostic target cannot be
imposed on heterogeneous action spaces, so the target is defined by the role it plays---the
scalar that the policy actually maximises or emits at the decision point---and is documented
per algorithm. For the Decision Transformer and for the deterministic continuous actor the
target is the allocation-aligned weight mass $\sum_k \hat{{w}}_k w_k(x)$, where
$w(x)$ is the simplex allocation after the policy's own action-to-weight transformation and
$\hat{{w}}$ is that allocation held fixed at the unperturbed observation; this preserves the
long-only, fully invested interpretation and reduces to a portfolio-weight distance under
perturbation. For the discrete-action value policy the target is the Q value of the greedily
selected action, and for the discrete stochastic policy it is the logit of the selected
action; in both cases the selected action is additionally mapped to its allocation so that
perturbation effects are also measured as an $L_1$ portfolio-weight distance and as an
action-flip rate. Attribution is never averaged over action heads the policy does not select.
Where a target's local gradient vanishes because the network saturates, a documented
pre-squash complementary target is used for the gradient-based method and the saturation is
reported rather than concealed.

\paragraph{{Diagnostics.}} Contribution is measured by group occlusion over
$(\text{{instrument}}, \text{{indicator}})$ groups and by integrated gradients under three
baselines (zero, training-period mean, and sampled training-period backgrounds), summarised as
feature-ranking stability across stratified bootstrap resamples and as concordance among
baselines. Necessity is measured by attribution-guided deletion of the top {fractions} of
feature groups against matched random deletions, and by occlusion of complete historical
timesteps. Structure is measured by $k$-nearest-neighbour overlap of the decision-proximal
latent representation under resampling, standardised input noise and low-importance masking,
and by the concentration of layer influence across depth. The layer used for each policy and
the layer-influence estimator applied to it are recorded per model, and estimators are never
mixed within a metric.

\paragraph{{Why dimensionless quantities.}} Attribution and activation magnitudes depend on the
scale of each network's parameters and on the units of its target, and the two families do not
even observe identical column sets. Raw magnitudes are therefore never compared across
architectures. Every cross-model quantity is a normalised share, a rank correlation, a
neighbourhood-overlap fraction or a concentration index, each bounded and unitless, and all
normalisation is performed within a model and sample before any comparison is made. Lag
profiles from policies with different lookback lengths are compared on a relative-lag axis in
$[0,1]$; the raw lag values are retained.
"""
    return body


def results_tex(
    table: pd.DataFrame,
    correlations: pd.DataFrame,
    bootstrap: pd.DataFrame,
    family: pd.DataFrame,
    matched: Optional[pd.DataFrame],
    settings: Dict[str, object],
) -> str:
    table = _view(table)
    dt = table.loc[table["family"] == "DT"]
    rl = table.loc[table["family"] == "RL"]
    n_models = len(table)

    computable = table[["C", "N", "S"]].notna().all(axis=1).sum()
    dims_all = int(table[["C", "N", "S"]].notna().all(axis=1).sum()) == n_models

    def fam_mean(frame: pd.DataFrame, col: str) -> str:
        return _num(pd.to_numeric(frame[col], errors="coerce").mean())

    spread_D = _range(table["D"])
    lo = table.loc[pd.to_numeric(table["D"], errors="coerce").idxmin()] if len(table) else None
    hi = table.loc[pd.to_numeric(table["D"], errors="coerce").idxmax()] if len(table) else None

    # association with performance, all models
    corr_all = correlations.loc[correlations["group"] == "all"] if len(correlations) else correlations
    corr_line = "not estimable: the correlation was not computed at this sample size"
    if len(corr_all):
        row = corr_all.loc[corr_all["score"] == "aggregate_diagnostic_score"]
        if len(row):
            r = row.iloc[0]
            n_corr = int(r.get("n", 0) or 0)
            if np.isfinite(float(r.get("spearman", np.nan) or np.nan)):
                corr_line = (
                    f"Spearman $\\rho={_num(r.get('spearman'), 2)}$ "
                    f"($p={_num(r.get('spearman_p'), 2)}$), Kendall "
                    f"$\\tau={_num(r.get('kendall'), 2)}$, on $n={n_corr}$ policies"
                )
            else:
                corr_line = (
                    f"not estimable: only $n={n_corr}$ policies carry both a diagnostic score and "
                    f"a portfolio outcome, below the minimum this pipeline will compute a rank "
                    f"correlation for"
                )

    # policies whose allocation is effectively constant over the evaluation window
    degenerate = [
        _esc(r["policy"])
        for _, r in table.iterrows()
        if np.isfinite(pd.to_numeric(r.get("weight_unique_rows"), errors="coerce"))
        and float(r["weight_unique_rows"]) <= 3
    ]
    deg_sentence = ""
    if degenerate:
        word = {1: "One", 2: "Two", 3: "Three", 4: "Four"}.get(len(degenerate), str(len(degenerate)))
        verb = "is" if len(degenerate) == 1 else "are"
        deg_sentence = (
            f" {word} of the included {'policy' if len(degenerate) == 1 else 'policies'} "
            f"({', '.join(degenerate)}) {verb} functionally degenerate: the allocation takes at "
            f"most three distinct values over the whole evaluation window. The diagnostics detect "
            f"this without reference to returns, because deleting any information leaves the "
            f"decision unchanged and the necessity dimension collapses accordingly."
        )

    nec_dt, nec_rl = fam_mean(dt, "N"), fam_mean(rl, "N")
    con_dt, con_rl = fam_mean(dt, "C"), fam_mean(rl, "C")
    str_dt, str_rl = fam_mean(dt, "S"), fam_mean(rl, "S")

    # A metric that takes nearly the same value for every policy carries no
    # discriminative information and is reported as such rather than as agreement.
    saturated = []
    for name, label in (
        ("contribution_rank_stability", "feature-ranking stability"),
        ("contribution_baseline_concordance", "baseline concordance"),
        ("deletion_faithfulness", "deletion faithfulness"),
        ("temporal_profile_stability", "temporal-profile stability"),
        ("latent_neighbourhood_stability", "latent-neighbourhood stability"),
        ("non_concentrated_layer_influence", "layer-influence dispersion"),
    ):
        if name not in table.columns:
            continue
        values = pd.to_numeric(table[name], errors="coerce").dropna()
        if len(values) == len(table) and float(values.min()) >= 0.99:
            saturated.append((label, float(values.min())))
    sat_sentence = ""
    if saturated:
        listed = ", ".join(f"{label} $\\geq {_num(low, 3)}$" for label, low in saturated)
        sat_sentence = (
            f" Not every metric contributes to that separation: {listed} for every policy, so "
            f"{'this metric is' if len(saturated) == 1 else 'these metrics are'} at the top of "
            f"the admissible range here and the ordering is driven by the remaining ones. That is "
            f"a property of this small, homogeneously trained policy set and a reason not to read "
            f"the dimension scores as calibrated across architectures."
        )

    # which policies supplied the primary ranking from gradients and which from perturbation
    grad_models, pert_models = [], []
    if "attribution_method" in table.columns:
        for _, r in table.iterrows():
            (grad_models if r["attribution_method"] == "integrated_gradients" else pert_models).append(
                _esc(r["policy"])
            )
    method_sentence = (
        "Both attribution estimators were computed for every policy."
        if not pert_models or not grad_models
        else (
            f"Integrated gradients supplied the primary ranking for "
            f"{', '.join(grad_models)}, whereas for {', '.join(pert_models)} the path gradients "
            f"vanish at the sampled observations and the perturbation-based group occlusion "
            f"supplied it instead"
        )
    )

    coverage = ", ".join(
        f"{_esc(a)} ({int((table['algorithm'] == a).sum())})" for a in sorted(set(table["algorithm"]))
    )

    matched_line = ""
    if matched is not None and len(matched):
        strata = matched.loc[:, ["lookback", "rebalancing_frequency"]].drop_duplicates()
        n_strata = len(strata)
        matched_line = (
            f" A matched descriptive comparison restricted to policies that share the asset "
            f"universe, the lookback and the rebalancing frequency is available for {n_strata} "
            f"{'stratum' if n_strata == 1 else 'strata'} and is reported in the supplement."
        )
    else:
        matched_line = (
            " No Decision Transformer and reinforcement-learning policy in this comparison share "
            "both lookback and rebalancing frequency, so no matched stratum could be formed; this "
            "is stated as a limitation rather than worked around."
        )

    boot_line = ""
    if bootstrap is not None and len(bootstrap):
        dims = ["contribution_score", "necessity_score", "structure_score"]
        overlapping = 0
        checked = 0
        for col in dims:
            a = bootstrap[(bootstrap["group"] == "DT") & (bootstrap["metric"] == col)]
            b = bootstrap[(bootstrap["group"] == "RL") & (bootstrap["metric"] == col)]
            if len(a) and len(b):
                checked += 1
                lo_a, hi_a = float(a.iloc[0]["lower"]), float(a.iloc[0]["upper"])
                lo_b, hi_b = float(b.iloc[0]["lower"]), float(b.iloc[0]["upper"])
                if np.isfinite([lo_a, hi_a, lo_b, hi_b]).all() and lo_a <= hi_b and lo_b <= hi_a:
                    overlapping += 1
        if checked:
            boot_line = (
                f" Bootstrap intervals for the family means overlap for {overlapping} of "
                f"{checked} dimensions."
            )

    body = rf"""% Auto-generated by scripts/run_cross_architecture_comparison.py -- do not edit by hand.
\subsection{{Cross-architecture comparison}}
\label{{sec:cross-architecture-results}}

Table~\ref{{tab:cross-architecture-summary}} reports the three dimension scores, the aggregate
diagnostic score and the realised Sharpe ratio for all {n_models} policies;
Figure~\ref{{fig:cross-architecture-heatmap}} shows the six underlying raw diagnostics and
Figure~\ref{{fig:cross-architecture-functional}} the temporal-occlusion and guided-deletion
curves.

\paragraph{{The framework is computable outside the Transformer family.}} All three dimensions
were obtained for {computable} of {n_models} policies{'' if dims_all else ', with the remaining entries reported as undefined rather than imputed'},
covering {coverage}. The only substitutions required were the documented
architecture-specific decision targets and, where a network saturates, the documented
pre-squash complementary target for the gradient-based estimator. No dimension had to be
dropped and no metric had to be redefined per family.

\paragraph{{The diagnostics separate policies.}} Aggregate diagnostic scores span
{spread_D} across the comparison{f", from {_esc(lo['policy'])} to {_esc(hi['policy'])}" if lo is not None and hi is not None else ""}.
Mean scores by family are contribution {con_dt} (DT) against {con_rl} (RL), necessity {nec_dt}
against {nec_rl}, and structure {str_dt} against {str_rl}.{deg_sentence}{sat_sentence}

\paragraph{{Similarities and differences.}} The similarity is procedural rather than numerical:
the same estimators run, return bounded values and rank the policies. The differences are
substantive and architecture dependent. Temporal-occlusion profiles do not share a shape across
families (Figure~\ref{{fig:cross-architecture-functional}}a), so the recency structure recovered
for the Decision Transformer should not be read as a property of allocation policies in general.
{method_sentence}; this is a property of those frozen networks, and the framework records it
instead of concealing it.

\paragraph{{Association with outcomes.}} Across all {n_models} policies the aggregate
diagnostic score and the Sharpe ratio are related as {corr_line}. Within-family correlations
are reported in the supplement where the number of policies permits; with
{len(rl)} reinforcement-learning {'policy' if len(rl) == 1 else 'policies'} and {len(dt)}
Decision Transformer {'checkpoint' if len(dt) == 1 else 'checkpoints'} these are descriptive
statistics and no inferential claim is made from them.{boot_line}{matched_line}

\paragraph{{Scope of the claim.}} The experiment supports two statements: the framework is
computable for non-Transformer policies, and the diagnostics differentiate the policies
examined. It does not support the claim that the diagnostics prospectively predict performance
across architectures; establishing that would require a policy population large enough to
separate the two.
"""
    return body


def discussion_tex(table: pd.DataFrame, settings: Dict[str, object]) -> str:
    table = _view(table)
    n_rl = int((table["family"] == "RL").sum())
    n_dt = int((table["family"] == "DT").sum())
    algos = sorted(set(table.loc[table["family"] == "RL", "algorithm"]))
    n_degenerate = int(
        (pd.to_numeric(table["weight_unique_rows"], errors="coerce") <= 3).sum()
    )
    degenerate_clause = (
        f"and {n_degenerate} of the frozen reinforcement-learning policies are close to "
        f"input-invariant, which bounds what any attribution method can report about them, "
        if n_degenerate
        else ""
    )
    visibility_clause = (
        f", and it made the degeneracy of {n_degenerate} "
        f"{'policy' if n_degenerate == 1 else 'policies'} visible from the diagnostics alone"
        if n_degenerate
        else ""
    )

    body = rf"""% Auto-generated by scripts/run_cross_architecture_comparison.py -- do not edit by hand.
\subsection{{Applicability beyond Transformer policies}}
\label{{sec:cross-architecture-discussion}}

Extending the diagnostics to {', '.join(_esc(a) for a in algos)} policies clarifies what the
framework depends on. Contribution, necessity and structure are defined on a differentiable
decision scalar, the observation window that produced it and the intermediate activations;
attention weights and return-to-go conditioning are used, where available, as convenient
implementations of those quantities rather than as prerequisites. The three dimensions were
computed for every included policy without redefining a metric per family, which indicates
that the audit procedure is not specific to the Decision Transformer.

At the same time the raw diagnostic profiles remain architecture dependent. Temporal-occlusion
shapes, attribution concentration and the depth distribution of decision influence differ
between the sequence model and the multilayer-perceptron policies, {degenerate_clause}so the
comparison does not licence transferring a numeric profile obtained for one architecture to
another. The values reported here are not architecture-independent constants.

What the framework provides is a common audit vocabulary. Two policies with different action
spaces, different observation sets and different inductive biases can be described with the same
bounded, dimensionless quantities---ranking stability, baseline concordance, deletion
faithfulness, profile stability, neighbourhood stability and layer-influence concentration---and
placed in the same table. That is useful for review and for pre-deployment scrutiny
independently of whether the underlying policies behave alike{visibility_clause}.

The benchmark does not establish universal cross-architecture thresholds. With {n_dt}
Decision Transformer {'checkpoint' if n_dt == 1 else 'checkpoints'} and {n_rl} reinforcement-learning
{'policy' if n_rl == 1 else 'policies'} the evidence is descriptive: it shows the instrument reads
across architectures, not what value of a reading should be considered acceptable. The
calibration reference distribution reported earlier was estimated on Decision Transformers and
was not recalibrated on these policies, and it should not be treated as a decision rule for
other architectures. Scoring the diagnostics against outcomes across families would require a
substantially larger and more diverse policy population, ideally with the observation set held
fixed so that input differences do not confound architecture differences.
"""
    return body
