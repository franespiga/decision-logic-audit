def write_reviewer_response(
    cash_regime: pd.DataFrame,
    shifts: pd.DataFrame,
    selected: pd.DataFrame,
    path: Path,
) -> None:
    hb, hc = "DT_max_quadratic_utility", "DT_16_10"

    def mean_ci(mid, regime):
        r = cash_regime.loc[
            (cash_regime["model_id"] == mid) & (cash_regime["regime"] == regime)
        ].iloc[0]
        return _fmt_ci(r["mean_cash"], r["ci95_low"], r["ci95_high"])

    sh = shifts.loc[
        (shifts["model_id"] == hb) & (shifts["contrast"] == "crash_minus_bull")
    ].iloc[0]
    perf_h = selected.loc[selected["model_id"] == hb].iloc[0]
    perf_l = selected.loc[selected["model_id"] == hc].iloc[0]

    text = f"""% Auto-generated by scripts/run_cash_outcome_link.py — do not edit by hand.
We thank the reviewer for encouraging a tighter link between the diagnostics and practical
portfolio outcomes. We have added a brief Results subsection that quantifies
regime-conditioned CASH allocation and equity exposure for the higher- and lower-Sharpe
Decision Transformer policies, with 95\\% moving-block bootstrap intervals on trading dates,
and relates these allocations to annualised volatility, maximum drawdown, turnover and Sharpe
(Table~\\ref{{tab:cash-outcome-main}}, Figure~\\ref{{fig:cash-outcome-main}}).
The higher-Sharpe policy raises mean CASH from {mean_ci(hb, 'bull_market')} in the bull
regime to {mean_ci(hb, 'crash_period')} in the crash regime
(crash$-$bull difference {_fmt_ci(sh['difference'], sh['ci95_low'], sh['ci95_high'])}),
whereas the lower-Sharpe policy maintains a high average cash weight in both regimes
({mean_ci(hc, 'bull_market')} vs {mean_ci(hc, 'crash_period')}).
These allocation profiles coincide with gross Sharpe ratios of
{_fmt(perf_h['gross_sharpe_ratio'])} and {_fmt(perf_l['gross_sharpe_ratio'])},
maximum drawdowns of {_fmt(perf_h['gross_max_drawdown'])} and {_fmt(perf_l['gross_max_drawdown'])},
and annualised turnovers of {_fmt(perf_h['annualised_turnover'])} and {_fmt(perf_l['annualised_turnover'])},
respectively. Full sample sizes, bootstrap settings, family-level performance/turnover
context and an event panel around the COVID crash are provided in the supplementary material.
We emphasise that the results are associative: they show how diagnostic patterns are
mirrored in allocations and risk--return profiles, and they do not claim that CASH activation
is a causal guarantee of drawdown control or that the diagnostics prospectively select policies.
"""
    path.write_text(text, encoding="utf-8")


