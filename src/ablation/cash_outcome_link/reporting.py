def write_subsection_tex(
    cash_regime: pd.DataFrame,
    shifts: pd.DataFrame,
    selected: pd.DataFrame,
    diagnostics: pd.DataFrame,
    path: Path,
    *,
    cost_bps: float = 20.0,
) -> None:
    def get(mid, regime, col):
        return cash_regime.loc[
            (cash_regime["model_id"] == mid) & (cash_regime["regime"] == regime), col
        ].iloc[0]

    def get_shift(mid):
        return shifts.loc[
            (shifts["model_id"] == mid) & (shifts["contrast"] == "crash_minus_bull")
        ].iloc[0]

    hb, hc = "DT_max_quadratic_utility", "DT_16_10"
    sh_h, sh_l = get_shift(hb), get_shift(hc)
    perf_h = selected.loc[selected["model_id"] == hb].iloc[0]
    perf_l = selected.loc[selected["model_id"] == hc].iloc[0]
    diag_h = diagnostics.loc[diagnostics["model_id"] == hb].iloc[0]
    diag_l = diagnostics.loc[diagnostics["model_id"] == hc].iloc[0]

    n_crash = int(get(hb, "crash_period", "n_decisions"))
    n_bull = int(get(hb, "bull_market", "n_decisions"))

    text = f"""% Auto-generated by scripts/run_cash_outcome_link.py — do not edit by hand.
\\subsection{{From diagnostic patterns to portfolio outcomes}}
\\label{{sec:cash-outcome}}

CASH is a practical audit variable for these long-only Decision Transformer policies:
it is the residual of equity exposure ($1-w_{{\\mathrm{{CASH}}}}$) and is directly observable
from the allocation. We therefore quantify how the higher- and lower-Sharpe checkpoints
deploy CASH across the paper market regimes, and how that allocation profile coincides
with volatility, drawdown, turnover and Sharpe. The analysis uses the validation-period
weight series of the two policies restricted to the trading calendar
(weekends and holidays removed), so regime statistics are not inflated by calendar fill.

In the crash regime the higher-Sharpe policy allocates mean CASH of
{_fmt_ci(get(hb,'crash_period','mean_cash'), get(hb,'crash_period','ci95_low'), get(hb,'crash_period','ci95_high'))},
against
{_fmt_ci(get(hb,'bull_market','mean_cash'), get(hb,'bull_market','ci95_low'), get(hb,'bull_market','ci95_high'))}
in the bull regime (crash$-$bull difference
{_fmt_ci(sh_h['difference'], sh_h['ci95_low'], sh_h['ci95_high'])};
$n_{{\\mathrm{{crash}}}}={n_crash}$, $n_{{\\mathrm{{bull}}}}={n_bull}$ trading decisions;
95\\% moving-block bootstrap intervals).
The lower-Sharpe policy maintains a high average cash weight across regimes, with crash and bull means of
{_fmt_ci(get(hc,'crash_period','mean_cash'), get(hc,'crash_period','ci95_low'), get(hc,'crash_period','ci95_high'))}
and
{_fmt_ci(get(hc,'bull_market','mean_cash'), get(hc,'bull_market','ci95_low'), get(hc,'bull_market','ci95_high'))}
(crash$-$bull
{_fmt_ci(sh_l['difference'], sh_l['ci95_low'], sh_l['ci95_high'])};
the interval includes zero, so a crash increase is not supported for this policy).
Figure~\\ref{{fig:cash-outcome-main}} and Table~\\ref{{tab:cash-outcome-main}} summarise the
regime pattern. This allocation contrast is consistent with the previously reported
temporal diagnostics: the higher-Sharpe policy has a lower temporal recency index
({_fmt(diag_h['temporal_recency_index'])} vs {_fmt(diag_l['temporal_recency_index'])})
and a different crash-regime occlusion profile, while CASH-action attribution under stress
(Section on risk exposure) indicates volatility-sensitive use of the cash head rather than
a constant cash park.

These allocation profiles are reflected in the realised outcome metrics on the same window.
The higher-Sharpe policy records gross Sharpe {_fmt(perf_h['gross_sharpe_ratio'])},
annualised volatility {_fmt(perf_h['gross_annualised_volatility'])},
maximum drawdown {_fmt(perf_h['gross_max_drawdown'])}
and annualised turnover {_fmt(perf_h['annualised_turnover'])};
the lower-Sharpe policy records
{_fmt(perf_l['gross_sharpe_ratio'])},
{_fmt(perf_l['gross_annualised_volatility'])},
{_fmt(perf_l['gross_max_drawdown'])}
and {_fmt(perf_l['annualised_turnover'])}, respectively.
High average cash deployment coincides with lower volatility but not with a superior
risk--return trade-off; the higher-Sharpe policy's crash CASH increase coincides with a more
active equity profile, higher turnover and a substantially higher Sharpe ratio.
Net of a {cost_bps:.0f}\\,bp one-way cost the Sharpe ratios
are {_fmt(perf_h['net_sharpe_ratio'])} and {_fmt(perf_l['net_sharpe_ratio'])}.

These results are retrospective associations on the validation window used throughout the
study. They do not establish that diagnostic scores prospectively select policies, nor that
CASH activation is a causal guarantee of drawdown control. The contribution is to make the
diagnostic framework operational by showing how identified patterns are mirrored in
allocations and in the associated risk--return profile.
"""
    path.write_text(text, encoding="utf-8")


